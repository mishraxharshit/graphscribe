"""Teaching text: how to read a line chart. Plain English, no assumed knowledge."""

LINE = """HOW TO READ A LINE CHART
1. The bottom axis (X) is usually time or order. Read the line from left to right.
2. The side axis (Y) is the thing being measured. Higher on the page means a bigger value.
3. If the line goes up, the value is growing. If it goes down, the value is shrinking.
4. A steeper line means faster change. A flat line means no change.
5. A sudden spike or dip is an outlier. Ask what happened at that moment.
6. The trend is the overall direction, ignoring the small wiggles.

WORDS YOU WILL MEET
- Mean (average): add everything up, divide by how many there are.
- Median: the middle value when you sort them. Extreme values do not move it.
- Outlier: a value far away from the others.
- R-squared: a number from 0 to 1. Near 1 means a straight line fits the data well.
"""
